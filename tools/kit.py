"""Build and check the starter kit in learn/.

Usage:
    python tools/kit.py          # rewrite learn/words.md, then check the kit
    python tools/kit.py --check  # only check the kit

The word list follows tools/top1000_ranked.txt (the EF top 1000, most frequent
first). The check reports every word in learn/texts.md and in the example
sentences of learn/grammar.md that is not in a vocabulary table. Plurals (-s,
-es), adverbs (-li), past forms (-ed) and agent nouns (-or) count as known when
their base word is in a table. Names are listed in NAMES.
"""

import re
import sys
from pathlib import Path

from coverage import GRAMMAR, SKIPPED, VOCAB_DIRS, ROOT, adverb_base, table_words

LEARN = ROOT / "learn"
NAMES = {"anna", "polska", "berlin", "warszawa", "uro", "europa"}

# English words whose first table match is a different word: the month May, not the verb.
OVERRIDE = {"may": "kan"}


def read_rows():
    """Yield (english cell, uro cell) for every vocabulary table row."""
    for folder in VOCAB_DIRS:
        for path in sorted((ROOT / folder).glob("*.md")):
            header = None
            for line in path.read_text(encoding="utf-8").splitlines():
                if not line.startswith("|"):
                    header = None
                    continue
                cells = [c.strip() for c in line.strip().strip("|").split("|")]
                if header is None:
                    header = cells
                    continue
                if set(line) <= set("|-: \t") or header[0].lower() != "english":
                    continue
                yield cells[0], cells[1]


def uro_forms():
    """Return {english head word: [uro form with its note, ...]}."""
    forms = {}
    for english, uro in read_rows():
        note = re.search(r"\((.*?)\)", english)
        for part in re.sub(r"\(.*?\)", " ", english).split("/"):
            part = re.sub(r"^to ", "", part.strip().lower())
            if not part or " " in part:
                continue
            entry = f"{uro} ({note.group(1)})" if note else uro
            known = forms.setdefault(part, [])
            if not any(e == uro or e.startswith(uro + " (") for e in known):
                known.append(entry)
    return forms


def write_words():
    ranked = [w.strip() for w in (ROOT / "tools" / "top1000_ranked.txt").read_text(encoding="utf-8").splitlines()
              if w.strip() and not w.startswith("#")]
    forms = uro_forms()
    tables = table_words()
    rows = []
    for word in ranked:
        low = word.lower()
        if low in SKIPPED:
            continue
        if low in OVERRIDE:
            uro = OVERRIDE[low]
        elif low in forms:
            uro = ", ".join(forms[low])
        elif low in GRAMMAR:
            uro = re.sub(r"\s*\(.*?\)", "", GRAMMAR[low])
        else:
            base = adverb_base(low, tables)
            uro = tables[base][0] + "li" if base else "?"
        rows.append((word, uro))
    lines = ["# The 1000 most common words", "",
             "The most common English words first, with their Uro words. Where a word has two forms, the default comes first.",
             "Generated by `python tools/kit.py`; change the vocabulary tables, not this file.", "",
             "| # | English | Uro |", "|--:|---------|-----|"]
    lines += [f"| {i} | {word} | {uro} |" for i, (word, uro) in enumerate(rows, 1)]
    (LEARN / "words.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"learn/words.md: {len(rows)} words, {sum(1 for _, u in rows if u == '?')} without a Uro word")


def known_words():
    words = set(NAMES)
    for _, uro in read_rows():
        words.update(re.findall(r"[a-z]+", re.sub(r"\(.*?\)", " ", uro.lower())))
    for uro in GRAMMAR.values():
        words.update(re.findall(r"[a-z]+", re.sub(r"\(.*?\)", " ", uro.lower())))
    return words


def is_known(word, words):
    if word in words:
        return True
    for ending in ("es", "s", "li", "ed", "d"):
        if word.endswith(ending) and word[:-len(ending)] in words:
            return True
    return word.endswith("or") and (word[:-2] in words or word[:-2] + "er" in words)


def uro_in_texts():
    """Yield the Uro column of each sentence table in learn/texts.md."""
    for line in (LEARN / "texts.md").read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and cells[0] != "Uro" and not set(line) <= set("|-: \t"):
            yield cells[0]


def uro_in_grammar():
    """Yield the example sentences (backticks with a space) of learn/grammar.md."""
    text = (LEARN / "grammar.md").read_text(encoding="utf-8")
    for span in re.findall(r"`([^`\n]+)`", text):
        if " " in span and "+" not in span and "…" not in span:
            yield span


def check():
    words = known_words()
    unknown = {}
    for name, sentences in (("texts.md", uro_in_texts()), ("grammar.md", uro_in_grammar())):
        for sentence in sentences:
            for word in re.findall(r"[a-z]+", sentence.lower()):
                if not is_known(word, words):
                    unknown.setdefault(word, f"{name}: {sentence}")
    for word, where in sorted(unknown.items()):
        print(f"unknown: {word:14} {where}")
    print(f"Unknown words: {len(unknown)}")
    return not unknown


def main():
    if "--check" not in sys.argv:
        write_words()
    sys.exit(0 if check() else 1)


if __name__ == "__main__":
    main()
